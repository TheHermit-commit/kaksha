const BY_CHAPTER = new Map<string, Video[]>();
for (const [chapterId, family, id, kind, title] of ROWS) {
  const key = `${family}:${chapterId}`;
  if (!BY_CHAPTER.has(key)) BY_CHAPTER.set(key, []);
  BY_CHAPTER.get(key)!.push({ id, kind, title });
}

function familyOf(exam: ExamId): Family {
  return exam === 'neet' ? 'neet' : 'jee';
}

/** Videos for a chapter, with the kind wanted listed first. Falls back to the other exam's list. */
export function videosFor(chapterId: string, exam: ExamId, prefer: Video['kind'] = 'lecture'): Video[] {
  const own = BY_CHAPTER.get(`${familyOf(exam)}:${chapterId}`);
  const other = BY_CHAPTER.get(`${familyOf(exam) === 'jee' ? 'neet' : 'jee'}:${chapterId}`);
  const list = [...(own ?? other ?? [])];
  return list.sort((a, b) => Number(b.kind === prefer) - Number(a.kind === prefer));
}

export function videoUrl(id: string): string {
  return `https://www.youtube.com/watch?v=${id}`;
}

export function youtubeSearchUrl(chapterName: string, exam: ExamId): string {
  const q = `${chapterName} one shot ${exam === 'neet' ? 'NEET' : 'JEE Main'} PYQs`;
  return `https://www.youtube.com/results?search_query=${encodeURIComponent(q)}`;
}
